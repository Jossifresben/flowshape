type Grid = (boolean | null)[][];

function placeFinder(grid: Grid, row: number, col: number): void {
  for (let r = -1; r <= 7; r++) {
    for (let c = -1; c <= 7; c++) {
      const rr = row + r;
      const cc = col + c;
      if (rr < 0 || rr >= grid.length || cc < 0 || cc >= grid.length) continue;
      const outer = r >= 0 && r <= 6 && (c === 0 || c === 6);
      const side = c >= 0 && c <= 6 && (r === 0 || r === 6);
      const core = r >= 2 && r <= 4 && c >= 2 && c <= 4;
      grid[rr]![cc] = outer || side || core;
    }
  }
}

/** Format information: 5 data bits (EC level + mask) with BCH(15,5) error
 *  correction, XOR-masked by 0x5412, written twice so either copy can be
 *  read if the other is damaged. */
function formatBits(mask: number): number {
  const data = (0b00 << 3) | mask; // 0b00 is level M
  let rem = data << 10;
  for (let i = 4; i >= 0; i--) {
    if ((rem >>> (i + 10)) & 1) rem ^= 0b10100110111 << i;
  }
  return ((data << 10) | rem) ^ 0b101010000010010;
}

/** Version information for versions 7 and up: 6 data bits with BCH(18,6). */
function versionBits(version: number): number {
  let rem = version << 12;
  for (let i = 5; i >= 0; i--) {
    if ((rem >>> (i + 12)) & 1) rem ^= 0b1111100100101 << i;
  }
  return (version << 12) | rem;
}

function maskAt(mask: number, row: number, col: number): boolean {
  switch (mask) {
    case 0: return (row + col) % 2 === 0;
    case 1: return row % 2 === 0;
    case 2: return col % 3 === 0;
    case 3: return (row + col) % 3 === 0;
    case 4: return (Math.floor(row / 2) + Math.floor(col / 3)) % 2 === 0;
    case 5: return ((row * col) % 2) + ((row * col) % 3) === 0;
    case 6: return (((row * col) % 2) + ((row * col) % 3)) % 2 === 0;
    default: return (((row + col) % 2) + ((row * col) % 3)) % 2 === 0;
  }
}

/** The four penalty rules the standard uses to pick a mask. Lower is better:
 *  they punish long same-colour runs, solid 2×2 blocks, patterns that look
 *  like a finder, and an unbalanced light/dark ratio. */
function penalty(m: boolean[][]): number {
  const n = m.length;
  let score = 0;

  // Rule 1: runs of five or more identical modules, by row and by column.
  for (let i = 0; i < n; i++) {
    for (const byRow of [true, false]) {
      let run = 1;
      for (let j = 1; j < n; j++) {
        const prev = byRow ? m[i]![j - 1]! : m[j - 1]![i]!;
        const cur = byRow ? m[i]![j]! : m[j]![i]!;
        if (cur === prev) {
          run++;
          if (run === 5) score += 3;
          else if (run > 5) score += 1;
        } else run = 1;
      }
    }
  }

  // Rule 2: every 2x2 block of one colour.
  for (let r = 0; r < n - 1; r++) {
    for (let c = 0; c < n - 1; c++) {
      const v = m[r]![c]!;
      if (m[r]![c + 1] === v && m[r + 1]![c] === v && m[r + 1]![c + 1] === v) score += 3;
    }
  }

  // Rule 3: the 1:1:3:1:1 finder-like sequence with four light modules on
  // either side, in both orientations.
  const A = [true, false, true, true, true, false, true, false, false, false, false];
  const B = [false, false, false, false, true, false, true, true, true, false, true];
  for (let i = 0; i < n; i++) {
    for (let j = 0; j + 11 <= n; j++) {
      let rowA = true, rowB = true, colA = true, colB = true;
      for (let k = 0; k < 11; k++) {
        if (m[i]![j + k] !== A[k]) rowA = false;
        if (m[i]![j + k] !== B[k]) rowB = false;
        if (m[j + k]![i] !== A[k]) colA = false;
        if (m[j + k]![i] !== B[k]) colB = false;
      }
      if (rowA) score += 40;
      if (rowB) score += 40;
      if (colA) score += 40;
      if (colB) score += 40;
    }
  }

  // Rule 4: deviation from an even split of dark and light.
  let dark = 0;
  for (const row of m) for (const v of row) if (v) dark++;
  const percent = (dark * 100) / (n * n);
  score += Math.floor(Math.abs(percent - 50) / 5) * 10;

  return score;
}

/** Builds the grid with everything but the data: the function patterns, and
 *  reserved (null) cells where format and version information will go. */
function functionGrid(version: number): Grid {
  const n = version * 4 + 17;
  const grid: Grid = Array.from({ length: n }, () => Array<boolean | null>(n).fill(null));

  placeFinder(grid, 0, 0);
  placeFinder(grid, 0, n - 7);
  placeFinder(grid, n - 7, 0);

  // Timing patterns.
  for (let i = 8; i < n - 8; i++) {
    grid[6]![i] = i % 2 === 0;
    grid[i]![6] = i % 2 === 0;
  }

  // Alignment patterns, except where they would collide with a finder.
  const centres = ALIGN[version - 1]!;
  for (const r of centres) {
    for (const c of centres) {
      if ((r === 6 && c === 6) || (r === 6 && c === n - 7) || (r === n - 7 && c === 6)) continue;
      for (let dr = -2; dr <= 2; dr++) {
        for (let dc = -2; dc <= 2; dc++) {
          grid[r + dr]![c + dc] = Math.max(Math.abs(dr), Math.abs(dc)) !== 1;
        }
      }
    }
  }

  // The dark module, always set, always here.
  grid[n - 8]![8] = true;

  // Reserve the format-information strips so data placement skips them.
  for (let i = 0; i < 9; i++) {
    if (grid[8]![i] === null) grid[8]![i] = false;
    if (grid[i]![8] === null) grid[i]![8] = false;
  }
  for (let i = 0; i < 8; i++) {
    if (grid[8]![n - 1 - i] === null) grid[8]![n - 1 - i] = false;
    if (grid[n - 1 - i]![8] === null) grid[n - 1 - i]![8] = false;
  }

  if (version >= 7) {
    const bits = versionBits(version);
    for (let i = 0; i < 18; i++) {
      const bit = ((bits >>> i) & 1) === 1;
      grid[Math.floor(i / 3)]![n - 11 + (i % 3)] = bit;
      grid[n - 11 + (i % 3)]![Math.floor(i / 3)] = bit;
    }
  }

  return grid;
}

/** Walks the data codewords into the grid: two-module-wide columns, right to
 *  left, alternating upward and downward, skipping the vertical timing
 *  pattern and every function module. */
function placeData(grid: Grid, codewords: Uint8Array): void {
  const n = grid.length;
  let bit = 0;
  let upward = true;
  for (let right = n - 1; right >= 1; right -= 2) {
    if (right === 6) right = 5; // the timing column is never part of a data column
    for (let step = 0; step < n; step++) {
      const row = upward ? n - 1 - step : step;
      for (const col of [right, right - 1]) {
        if (grid[row]![col] !== null) continue;
        const byte = codewords[bit >>> 3];
        // Past the last codeword lie the remainder bits, which are always 0.
        grid[row]![col] = byte !== undefined && ((byte >>> (7 - (bit & 7))) & 1) === 1;
        bit++;
      }
    }
    upward = !upward;
  }
}

function writeFormat(m: boolean[][], mask: number): void {
  const n = m.length;
  const bits = formatBits(mask);
  for (let i = 0; i < 15; i++) {
    const bit = ((bits >>> i) & 1) === 1;
    // First copy, around the top-left finder; second split between the other two.
    if (i < 6) m[i]![8] = bit;
    else if (i === 6) m[7]![8] = bit;
    else if (i === 7) m[8]![8] = bit;
    else if (i === 8) m[8]![7] = bit;
    else m[8]![14 - i] = bit;

    if (i < 8) m[8]![n - 1 - i] = bit;
    else m[n - 15 + i]![8] = bit;
  }
}

/**
 * Encodes `text` as a QR code and returns its modules: `matrix[row][col]`,
 * true where the module is dark. No quiet zone — the caller adds it, because
 * how much margin to leave is a rendering decision.
 *
 * `forceMask` overrides the automatic mask choice. Production never passes it;
 * it exists so the conformance test can compare all eight masked symbols
 * against a reference encoder. Mask choice affects only how easily a scanner
 * reads the code, never whether it decodes — the symbol records which mask was
 * used — so pinning it is safe.
 */
export function qrMatrix(text: string, forceMask?: number): boolean[][] {
  const bytes = new TextEncoder().encode(text);
  const version = chooseVersion(bytes.length);
  const codewords = buildCodewords(bytes, version);

  const base = functionGrid(version);
  placeData(base, codewords);

  // Which cells are data (maskable) is a property of the function grid, so it
  // is captured before the data goes in — masking must not touch a function
  // module.
  const reserved = functionGrid(version).map((row) => row.map((v) => v !== null));

  let best: boolean[][] | undefined;
  let bestScore = Infinity;
  for (let mask = 0; mask < 8; mask++) {
    if (forceMask !== undefined && mask !== forceMask) continue;
    const candidate = base.map((row, r) =>
      row.map((v, c) => (reserved[r]![c] ? v === true : (v === true) !== maskAt(mask, r, c))),
    );
    writeFormat(candidate, mask);
    const score = penalty(candidate);
    if (score < bestScore) {
      bestScore = score;
      best = candidate;
    }
  }
  return best!;
}
