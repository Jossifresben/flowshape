/**
 * A QR encoder, in-house.
 *
 * The site ships no runtime dependencies — that is the standing rule, and a
 * QR library would be the first. The format is a published standard
 * (ISO/IEC 18004) and the whole encoder is table-driven, so writing it is a
 * bounded exercise rather than an open-ended one.
 *
 * Scope is deliberately narrow: byte mode, error-correction level M, one
 * function that returns a matrix of modules. That is everything a share link
 * needs. Byte mode encodes any URL without the alphanumeric mode's
 * uppercase-only restriction; level M (≈15% recovery) is the usual choice for
 * a code that will be photographed off a screen at an angle. Supporting the
 * other three levels would triple the block table below and buy nothing.
 *
 * `tests/core/qr.test.ts` checks the output module-for-module against vectors
 * produced by an independent reference encoder, which is the only way to know
 * this is right — a QR that is subtly wrong still looks exactly like a QR.
 */

