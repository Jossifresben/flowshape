// ---------------------------------------------------------------------------
// GF(256) arithmetic, for Reed-Solomon. The field is generated by x^8+x^4+x^3+x^2+1
// (0x11d), the primitive polynomial the QR standard specifies.
// ---------------------------------------------------------------------------

const EXP = new Uint8Array(512);
const LOG = new Uint8Array(256);
{
  let x = 1;
  for (let i = 0; i < 255; i++) {
    EXP[i] = x;
    LOG[x] = i;
    x <<= 1;
    if (x & 0x100) x ^= 0x11d;
  }
  for (let i = 255; i < 512; i++) EXP[i] = EXP[i - 255]!;
}

function gfMul(a: number, b: number): number {
  if (a === 0 || b === 0) return 0;
  return EXP[LOG[a]! + LOG[b]!]!;
}

/** The generator polynomial for `degree` EC codewords: ∏(x − α^i). */
function generatorPoly(degree: number): Uint8Array {
  let poly = new Uint8Array([1]);
  for (let i = 0; i < degree; i++) {
    const next = new Uint8Array(poly.length + 1);
    for (let j = 0; j < poly.length; j++) {
      next[j] = next[j]! ^ poly[j]!;
      next[j + 1] = next[j + 1]! ^ gfMul(poly[j]!, EXP[i]!);
    }
    poly = next;
  }
  return poly;
}

/** The EC codewords for one data block: the remainder of data·x^degree
 *  divided by the generator polynomial. */
function ecCodewords(data: Uint8Array, degree: number): Uint8Array {
  const gen = generatorPoly(degree);
  const rem = new Uint8Array(data.length + degree);
  rem.set(data);
  for (let i = 0; i < data.length; i++) {
    const factor = rem[i]!;
    if (factor === 0) continue;
    for (let j = 0; j < gen.length; j++) rem[i + j] = rem[i + j]! ^ gfMul(gen[j]!, factor);
  }
  return rem.slice(data.length);
}

// ---------------------------------------------------------------------------
// Bit stream
// ---------------------------------------------------------------------------

class BitBuffer {
  readonly bits: number[] = [];
  put(value: number, length: number): void {
    for (let i = length - 1; i >= 0; i--) this.bits.push((value >>> i) & 1);
  }
}

/** Total data codewords a version holds at level M. */
function dataCapacity(version: number): number {
  const [, groups] = RS_BLOCKS[version - 1]!;
  let total = 0;
  for (const [count, per] of groups) total += count * per;
  return total;
}

/** Byte mode's character-count field is 8 bits up to version 9 and 16 bits
 *  from version 10 — the one place where version changes the header size, and
 *  therefore the one place a naive capacity check goes wrong. */
function countBits(version: number): number {
  return version < 10 ? 8 : 16;
}

/** The smallest version that fits `byteLength` bytes in byte mode at level M. */
function chooseVersion(byteLength: number): number {
  for (let v = 1; v <= 40; v++) {
    // 4 bits of mode indicator + the character count field.
    const needed = 4 + countBits(v) + byteLength * 8;
    if (needed <= dataCapacity(v) * 8) return v;
  }
  throw new Error(`qr: ${byteLength} bytes exceeds the capacity of a version 40 code at level M`);
}

/** Mode indicator, character count, payload, terminator and padding, split
 *  into blocks and interleaved with each block's EC codewords. */
function buildCodewords(bytes: Uint8Array, version: number): Uint8Array {
  const buf = new BitBuffer();
  buf.put(0b0100, 4);                       // byte mode
  buf.put(bytes.length, countBits(version));
  for (const b of bytes) buf.put(b, 8);

  const capacityBits = dataCapacity(version) * 8;
  // Terminator: up to four zero bits, truncated if the code is nearly full.
  buf.put(0, Math.min(4, capacityBits - buf.bits.length));
  while (buf.bits.length % 8 !== 0) buf.bits.push(0);

  const data = new Uint8Array(dataCapacity(version));
  for (let i = 0; i < buf.bits.length; i += 8) {
    let byte = 0;
    for (let j = 0; j < 8; j++) byte = (byte << 1) | buf.bits[i + j]!;
    data[i / 8] = byte;
  }
  // The spec's alternating pad bytes fill whatever remains.
  for (let i = buf.bits.length / 8, alt = 0; i < data.length; i++, alt++) {
    data[i] = alt % 2 === 0 ? 0xec : 0x11;
  }

  const [ecPerBlock, groups] = RS_BLOCKS[version - 1]!;
  const dataBlocks: Uint8Array[] = [];
  const ecBlocks: Uint8Array[] = [];
  let offset = 0;
  for (const [count, per] of groups) {
    for (let i = 0; i < count; i++) {
      const block = data.slice(offset, offset + per);
      offset += per;
      dataBlocks.push(block);
      ecBlocks.push(ecCodewords(block, ecPerBlock));
    }
  }

  // Interleave: the nth codeword of every block in turn, data first, then EC.
  // Blocks differ in length by at most one, so the longer ones simply
  // contribute nothing on the final pass.
  const out: number[] = [];
  const maxData = Math.max(...dataBlocks.map((b) => b.length));
  for (let i = 0; i < maxData; i++) {
    for (const block of dataBlocks) if (i < block.length) out.push(block[i]!);
  }
  for (let i = 0; i < ecPerBlock; i++) {
    for (const block of ecBlocks) out.push(block[i]!);
  }
  return new Uint8Array(out);
}

